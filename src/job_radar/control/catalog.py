def tr(language: str, key: str, **values) -> str:
    return (
        CATALOG.get(language, CATALOG["uk"]).get(key, CATALOG["en"].get(key, key)).format(**values)
    )


def label(language: str, value) -> str:
    value = str(value or "unknown")
    if value in LABELS:
        return LABELS[value][{"uk": 0, "de": 1, "en": 2}.get(language, 0)]
    return tr(language, value)
